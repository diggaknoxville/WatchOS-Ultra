#!/usr/bin/env python3
"""Build the KRONOS icon font (Material Symbols Rounded, Apache-2.0).

  python3 tools/fonts/build_icons.py

Produces src/fonts/font_icons.h (subset TTF for LVGL tiny_ttf) and
include/ui/Icons.h (named UTF-8 string constants, e.g. ICO_CALENDAR).
"""
import os
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools import subset

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")
SRC = os.path.join(HERE, "MaterialSymbolsRounded[FILL,GRAD,opsz,wght].ttf")
CODEPOINTS = os.path.join(HERE, "MaterialSymbolsRounded[FILL,GRAD,opsz,wght].codepoints")

ICONS = """
apps grid_view widgets home arrow_back arrow_forward chevron_left chevron_right expand_more expand_less
close check add remove delete edit refresh sync search tune more_horiz
calendar_month event today schedule alarm add_alarm snooze timer hourglass_top history update
navigation near_me my_location location_on location_searching gps_fixed gps_off explore map route
directions_walk directions_car directions_bike directions_run hiking flag sports_score
turn_left turn_right turn_slight_left turn_slight_right turn_sharp_left turn_sharp_right straight
u_turn_left u_turn_right roundabout_left roundabout_right merge fork_left fork_right ramp_left ramp_right
north speed zoom_in zoom_out layers travel_explore place star
local_gas_station restaurant local_cafe local_parking local_hospital local_pharmacy shopping_cart
hotel train directions_bus atm wc
settings notifications notifications_active notifications_off do_not_disturb_on
bolt battery_full battery_charging_full battery_alert wifi wifi_off satellite_alt cell_tower podcasts radar
sos emergency flashlight_on vibration volume_up volume_off visibility brightness_6 light_mode dark_mode
palette watch qr_code_2 smartphone info power_settings_new restart_alt bedtime
footprint local_fire_department favorite monitor_heart sensors memory thermostat speed
stop play_arrow pause skip_next timer_off
keyboard backspace space_bar keyboard_return lock
call mail chat groups wb_sunny nights_stay cloud water_drop terrain
""".split()


def main():
    cps = {}
    for line in open(CODEPOINTS):
        name, cp = line.split()
        cps[name] = int(cp, 16)
    missing = [n for n in ICONS if n not in cps]
    if missing:
        print("missing (skipped):", missing)
    icons = [n for n in dict.fromkeys(ICONS) if n in cps]

    font = instancer.instantiateVariableFont(TTFont(SRC), {"FILL": 1, "GRAD": 0, "opsz": 40, "wght": 500})
    opts = subset.Options()
    opts.hinting = False
    opts.layout_features = []                     # no ligatures needed: we address by codepoint
    opts.drop_tables += ["GSUB", "GPOS"]
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=[cps[n] for n in icons])
    sub.subset(font)
    tmp = os.path.join(HERE, "icons_sub.ttf")
    font.save(tmp)
    data = open(tmp, "rb").read()
    os.remove(tmp)

    with open(os.path.join(ROOT, "src", "fonts", "font_icons.h"), "w") as f:
        f.write("#pragma once\n#include <stdint.h>\n")
        f.write(f"// Material Symbols Rounded (Apache-2.0), filled, wght 500, {len(icons)} icons ({len(data)} bytes)\n")
        f.write("// Rebuild: python3 tools/fonts/build_icons.py\n")
        f.write("static const uint8_t icons_ttf[] = {\n")
        for i in range(0, len(data), 16):
            f.write("  " + ",".join(str(b) for b in data[i:i + 16]) + ",\n")
        f.write("};\n")
        f.write(f"static const unsigned int icons_ttf_len = {len(data)};\n")

    with open(os.path.join(ROOT, "include", "ui", "Icons.h"), "w") as f:
        f.write("#pragma once\n// Generated by tools/fonts/build_icons.py - Material Symbols Rounded codepoints\n")
        f.write("// Use with ui::F.ico* fonts, e.g. ui::label(p, ui::F.icoM, c, ICO_CALENDAR_MONTH)\n\n")
        for n in icons:
            utf8 = chr(cps[n]).encode("utf-8")
            esc = "".join(f"\\x{b:02X}" for b in utf8)
            f.write(f"#define ICO_{n.upper():28s} \"{esc}\"\n")
    print(f"{len(icons)} icons, {len(data)} bytes")


if __name__ == "__main__":
    main()
